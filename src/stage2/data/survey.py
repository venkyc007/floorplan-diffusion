"""Pass 1 of the data build: decide which appliance sub-types count as "appliance".

    python -m src.stage2.data.survey --root <CubiCasa root> [--workers 4] [--limit N]

User rule (2026-10-17): appliance = kitchen appliances only. Every appliance
candidate instance (classes16.yaml `appliance_candidate`) is assigned the room type
it stands in (the most common room type under its outline, before fixtures are
painted). A sub-type is an appliance if >= 50% of its instances stand in kitchens;
otherwise it is ignored (the room underneath stays).

Train split only, untyped plans excluded (like all statistics). Writes
configs/stage2/appliance_subtypes.yaml: the chosen list + the full count table.
"""

import argparse
import datetime
from multiprocessing import Pool

import numpy as np
import yaml

from src.stage2.data.build_cubicasa import CFG, find_root, read_split_lists
from src.stage2.data.classes16 import CONFIG, C16
from src.stage2.data.cubicasa_svg import parse_svg, wall_thickness
from src.stage2.data.rasterise import _fill, draw_labels, frame_size, untyped_rooms

OUT = CONFIG.parent / "appliance_subtypes.yaml"
ROOM_NAMES = [C16.names[c] for c in C16.group("S")] + ["none"]


def survey_plan(job):
    """One plan -> {sub-type key: {room type: count}} for appliance candidates (or None if skipped)."""
    split, rel, root = job
    try:
        import cv2
        plan = parse_svg(f"{root}/{rel}/model.svg", appliance_subtypes="all")
        t, n = wall_thickness(plan)
        if n == 0 or not np.isfinite(t):
            return None
        im = cv2.imread(f"{root}/{rel}/F1_scaled.png", cv2.IMREAD_UNCHANGED)
        frame = im.shape[:2]
    except Exception:
        return None
    s = CFG["completion_set"]["wall_px"] / t
    label, before = draw_labels(plan, frame, s)
    rooms = np.isin(label, C16.group("S"))
    if rooms.any() and untyped_rooms(plan, frame, s, label).sum() > C16.cfg["untyped_max_share"] * rooms.sum():
        return {"__untyped__": True}
    out = {}
    for sh in plan.of_kind("fixture"):
        if C16.fixture_target(sh.name.split())[0] != "appliance_candidate":
            continue
        m = np.zeros(frame_size(frame, s), np.uint8)
        _fill(m, sh.points, s, 1)
        under = before[m > 0]
        under = under[np.isin(under, C16.group("S"))]
        room = C16.names[np.bincount(under).argmax()] if len(under) else "none"
        out.setdefault(sh.key, {}).setdefault(room, 0)
        out[sh.key][room] += 1
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", required=True)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args()
    root = find_root(args.root)
    jobs = [(s, r, str(root)) for s, r in read_split_lists(root) if s == "train"]
    if args.limit:
        jobs = jobs[: args.limit]
    table, n_untyped, n_skipped = {}, 0, 0
    with Pool(args.workers) as pool:
        for res in pool.imap_unordered(survey_plan, jobs, chunksize=8):
            if res is None:
                n_skipped += 1
            elif "__untyped__" in res:
                n_untyped += 1
            else:
                for key, rooms in res.items():
                    for room, c in rooms.items():
                        table.setdefault(key, {}).setdefault(room, 0)
                        table[key][room] += c
    share = C16.cfg["appliance_min_kitchen_share"]
    chosen, rows = [], {}
    for key, rooms in sorted(table.items(), key=lambda kv: -sum(kv[1].values())):
        total = sum(rooms.values())
        kitchen = rooms.get("kitchen", 0) / total
        if kitchen >= share:
            chosen.append(key)
        rows[key] = {"instances": total, "kitchen_share": round(kitchen, 3), "appliance": kitchen >= share,
                     "rooms": {r: rooms.get(r, 0) for r in ROOM_NAMES if rooms.get(r, 0)}}
    doc = {"appliance": chosen,
           "rule": f"sub-type is an appliance if >= {share:.0%} of its instances stand in kitchens",
           "source": f"CubiCasa5K train split, {len(jobs) - n_untyped - n_skipped} typed plans "
                     f"({n_untyped} untyped and {n_skipped} unreadable plans excluded), {datetime.date.today()}",
           "table": rows}
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("# GENERATED by python -m src.stage2.data.survey. Do not edit by hand.\n")
        yaml.safe_dump(doc, f, sort_keys=False, allow_unicode=True, width=120)
    print(open(args.out, encoding="utf-8").read(), flush=True)


if __name__ == "__main__":
    main()
