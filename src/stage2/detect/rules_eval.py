"""Tune and check the rule-based detector on full val plans (laptop, CPU).

    python -m src.stage2.detect.rules_eval tune   --zip completion_val.zip  -> configs/stage2/detect_rules.yaml
    python -m src.stage2.detect.rules_eval check  --zip completion_val.zip  -> outputs/stage2/rules_check.md
    python -m src.stage2.detect.rules_eval figure --zip completion_val.zip  -> outputs/stage2/omission_examples.png

Plans: the typed val plans in a fixed random order (seed 0): plans 0-199 tune the thresholds
(intact), plans 200-299 measure false alarms (intact, never used for tuning); the omission check
draws 300 plans (seed 1) with ONE simulated omission each.

Tuning (greedy): every rule starts with threshold 0 (all its candidates kept). While the total
false alarms on the 200 intact plans exceed 0.5 per plan, the rule with the most false alarms
raises its threshold just above its lowest kept score. Any candidate on an intact plan is a false
alarm (counted before merging).
A simulated omission is DETECTED if a candidate box (after thresholds and merging) overlaps its
omitted pixels; TYPE-CORRECT if that candidate also has the omission's type.
"""

import argparse
import datetime
from collections import Counter, defaultdict

import numpy as np
import yaml

from src.stage2.complete.data16 import load_plans
from src.stage2.data.classes16 import C16
from src.stage2.detect.omissions import KINDS, simulate_one
from src.stage2.detect.rules import ALL_RULES, THRESHOLDS_FILE, detect, raw_candidates
from src.utils import PROJECT_ROOT

OUT = PROJECT_ROOT / "outputs" / "stage2"
BUDGET = 0.5


def ordered_plans(zip_path):
    plans = load_plans(zip_path)
    order = np.random.default_rng(0).permutation(len(plans))
    return [plans[i] for i in order]


def tune(args):
    plans = ordered_plans(args.zip)[:200]
    scores = defaultdict(list)
    for i, (_, lab) in enumerate(plans):
        for c in raw_candidates(lab):
            scores[c.rules[0]].append(c.score)
        if (i + 1) % 20 == 0:
            print(f"tune: {i + 1}/{len(plans)} plans", flush=True)
    n = len(plans)
    th = {r: 0.0 for r in ALL_RULES}
    srt = {r: sorted(scores[r]) for r in ALL_RULES}
    kept = {r: len(srt[r]) for r in ALL_RULES}            # candidates with score >= th
    while sum(kept.values()) / n > BUDGET:
        r = max(kept, key=kept.get)
        lo = srt[r][len(srt[r]) - kept[r]]                 # lowest kept score
        above = [s for s in srt[r] if s > lo]
        th[r] = above[0] if above else float("inf")
        kept[r] = len(above)
    fa = {r: kept[r] / n for r in ALL_RULES}
    doc = {"thresholds": {r: (float(v) if np.isfinite(v) else 1e12) for r, v in th.items()},
           "false_alarms_per_plan": {r: round(v, 3) for r, v in fa.items()},
           "raw_candidates_per_plan": {r: round(len(srt[r]) / n, 3) for r in ALL_RULES},
           "source": f"{n} intact typed val plans (completion scale), budget {BUDGET} false alarms per plan, "
                     f"{datetime.date.today()}"}
    THRESHOLDS_FILE.write_text("# GENERATED by python -m src.stage2.detect.rules_eval tune\n" +
                               yaml.safe_dump(doc, sort_keys=False), encoding="utf-8")
    print(yaml.safe_dump(doc, sort_keys=False))


def hit(cands, mask, typ):
    found = correct = False
    for c in cands:
        y0, x0, y1, x1 = c.box
        if mask[y0:y1 + 1, x0:x1 + 1].any():
            found = True
            correct |= c.type == typ
    return found, correct


def check(args):
    th = yaml.safe_load(THRESHOLDS_FILE.read_text(encoding="utf-8"))
    plans = ordered_plans(args.zip)
    intact = plans[200:300]
    fa = Counter()
    n_cand = 0
    for _, lab in intact:
        cands = detect(lab, th["thresholds"])
        n_cand += len(cands)
        for c in cands:
            fa[c.rules[0]] += 1
    rng = np.random.default_rng(1)
    rows = []
    for i in range(args.n):
        pid, lab = plans[rng.integers(len(plans))]
        kind = KINDS[i % len(KINDS)]
        s = simulate_one(lab, rng, kind)
        if s is None:
            continue
        cands = detect(s["plan"], th["thresholds"])
        found, correct = hit(cands, s["mask"], s["type"])
        rows.append({**{k: s[k] for k in ("kind", "type", "location", "size_bin")}, "found": found,
                     "correct": correct, "n_cands": len(cands)})
        if (i + 1) % 50 == 0:
            print(f"check: {i + 1}/{args.n}", flush=True)
    import pandas as pd
    df = pd.DataFrame(rows)

    def table(by):
        g = df.groupby(by).agg(n=("found", "size"), detected=("found", "mean"), type_correct=("correct", "mean"))
        lines = [f"| {by} | n | detected | type-correct |", "|---|---|---|---|"]
        lines += [f"| {k} | {r.n} | {100 * r.detected:.0f}% | {100 * r.type_correct:.0f}% |" for k, r in g.iterrows()]
        return lines
    L = ["# Rule-based detector: check on simulated omissions", "",
         f"Thresholds: `configs/stage2/detect_rules.yaml` (tuned on 200 intact val plans, <= {BUDGET} false alarms per "
         f"plan). {len(df)} val plans with ONE simulated omission each (seed 1, omission kinds in turn); a detection = "
         "a candidate box (after thresholds and merging) overlapping the omitted pixels; type-correct = that "
         "candidate also has the right type.", "",
         f"**False alarms on 100 other intact val plans: {n_cand / len(intact):.2f} candidates per plan** "
         f"(by first rule: {', '.join(f'{r} {v / len(intact):.2f}' for r, v in fa.most_common())}).", "",
         f"**Overall: detected {100 * df.found.mean():.0f}%, type-correct {100 * df.correct.mean():.0f}%; "
         f"candidates per omitted plan {df.n_cands.mean():.2f}.**", ""]
    for by in ("kind", "location", "size_bin"):
        L += table(by) + [""]
    L += ["Thresholds and false alarms per rule on the 200 tuning plans:", "",
          "| rule | threshold (score) | false alarms / plan | raw candidates / plan |", "|---|---|---|---|"]
    L += [f"| {r} | {th['thresholds'][r]:.4g} | {th['false_alarms_per_plan'][r]:.3f} | {th['raw_candidates_per_plan'][r]:.2f} |"
          for r in ALL_RULES]
    (OUT / "rules_check.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


def figure(args):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plans = ordered_plans(args.zip)[:12]
    rng = np.random.default_rng(2)
    fig, axes = plt.subplots(6, 6, figsize=(18, 18))
    for i, (pid, lab) in enumerate(plans):
        s = simulate_one(lab, rng, KINDS[i % len(KINDS)])
        a, b, c = axes[i // 2, 3 * (i % 2):3 * (i % 2) + 3]
        a.imshow(C16.colourise(lab), interpolation="nearest")
        a.set_title(f"{pid[-28:]}", fontsize=7)
        if s is None:
            continue
        b.imshow(C16.colourise(s["plan"]), interpolation="nearest")
        b.set_title(f"omitted: {s['kind']} ({s['location']}, {s['size_bin']})", fontsize=7)
        over = C16.colourise(s["plan"]).astype(float) / 255 * 0.35 + 0.65
        over[s["mask"]] = (0.9, 0, 0)
        c.imshow(over, interpolation="nearest")
        c.set_title(f"missing: {s['type']} ({int(s['mask'].sum())} px)", fontsize=7)
    for ax in axes.ravel():
        ax.axis("off")
    fig.tight_layout()
    fig.savefig(OUT / "omission_examples.png", dpi=80)
    print("saved", OUT / "omission_examples.png")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("what", choices=["tune", "check", "figure"])
    ap.add_argument("--zip", required=True)
    ap.add_argument("--n", type=int, default=300)
    a = ap.parse_args()
    {"tune": tune, "check": check, "figure": figure}[a.what](a)
