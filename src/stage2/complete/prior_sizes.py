"""Median component sizes for the sketch prior (completion scale, walls 3 px), measured on the TUNING val plans.

    python -m src.stage2.complete.prior_sizes --zip completion_val.zip --tuning tuning_ids.txt
        -> configs/stage2/sketch_prior.yaml

door / window: median length along the wall (longer side of the component's box) and thickness (shorter side).
fixtures: median box height x width per class (shorter side first).
"""

import argparse
from pathlib import Path

import numpy as np
import yaml

from src.stage2.complete.data16 import load_plans
from src.stage2.constraints.rules import components
from src.stage2.data.classes16 import C16
from src.utils import PROJECT_ROOT

OUT = PROJECT_ROOT / "configs" / "stage2" / "sketch_prior.yaml"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--zip", required=True)
    ap.add_argument("--tuning", required=True)
    args = ap.parse_args()
    keep = set(Path(args.tuning).read_text(encoding="utf-8").split())
    sizes = {n: [] for n in ["door", "window"] + list(C16.cfg["groups"]["F"])}
    for pid, lab in load_plans(args.zip):
        if pid not in keep:
            continue
        for n in sizes:
            for m in components(lab == C16.index[n]):
                ys, xs = np.nonzero(m)
                a, b = ys.max() - ys.min() + 1, xs.max() - xs.min() + 1
                if m.sum() >= 6:
                    sizes[n].append((min(a, b), max(a, b)))
    out = {"source": f"median component box (short, long side) over {len(keep)} tuning val plans, completion scale",
           "sizes": {n: [int(np.median([s[0] for s in v])), int(np.median([s[1] for s in v]))] for n, v in sizes.items()},
           "counts": {n: len(v) for n, v in sizes.items()}}
    OUT.write_text("# GENERATED by python -m src.stage2.complete.prior_sizes\n" + yaml.safe_dump(out, sort_keys=False),
                   encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
